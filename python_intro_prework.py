# A coffee shop offers a 35% discount on orders for students only.
# Customers are asked to verify student status to determine if they qualify.

name = input("What is your name?: ")
student_status = input("Are you a student with a valid school ID?: ")
base_price = input("Enter the order total: ")

# 35% discount is applied if student status is verified
if student_status == "yes":
  percent_discount = float(base_price) * .35
  discount_price = float(base_price) - float(percent_discount)
  student_price = round(discount_price,2)
  print("Hello " + str(name) +
        ", your total with the student discount is $" +
        str(student_price) + ".")
else: print("Hello " + str(name) + ", your total is $" + str(base_price) + ".")

